"""Score the vendor desk agent on all 12 practice documents.

Runs agent.review on every file in data/practice_docs/, checks the six key
fields against data/practice_key.json, and writes output/practice_scores.md.
Documents are read as they are, with no cleaning, so this is also the
undefended baseline for the prompt-injection problems.

Run from HW6/:  .venv/Scripts/python scripts/score_practice.py
"""

import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from agent import MODEL_NAME, NO_DEFENSES, ROOT, SETTINGS, review  # noqa: E402

FIELDS = ["vendor", "sku", "unit_price", "lead_time_days", "min_order", "decision"]
DOCS = ROOT / "data" / "practice_docs"
OUT = ROOT / "output" / "practice_scores.md"
KEY = json.loads((ROOT / "data" / "practice_key.json").read_text(encoding="utf-8"))


async def main() -> None:
    rows = []
    for k in KEY:
        report, usage = await review(DOCS / k["file"], label="practice_agent", defenses=NO_DEFENSES)
        got = report.model_dump()
        wrong = [f for f in FIELDS if got[f] != k[f]]
        rows.append((k, got, wrong, usage))
        print(f"{k['file']:28} {'OK' if not wrong else 'WRONG ' + ','.join(wrong):30} "
              f"cached={usage.cached_tokens:,}/{usage.input_tokens:,} out={usage.output_tokens} ${usage.cost_usd:.6f}")
    write_report(rows)


def write_report(rows: list) -> None:
    full = sum(not w for _, _, w, _ in rows)
    fields = sum(len(FIELDS) - len(w) for _, _, w, _ in rows)
    decisions = sum("decision" not in w for _, _, w, _ in rows)
    cost = sum(u.cost_usd for *_, u in rows)
    warm = [u for *_, u in rows][1:]
    lines = [
        "# Practice Document Scores (HW6)",
        "",
        f"The vendor desk agent (`agent.py`) on all 12 practice documents, scored against `data/practice_key.json` "
        f"on vendor, SKU, unit price, lead time, minimum order and decision. Model: {MODEL_NAME} (reasoning effort "
        f"`{SETTINGS.get('openai_reasoning_effort')}`). Documents are read as they are, with no cleaning of hidden text, "
        "so this is also the **undefended baseline** for the prompt-injection problems. Generated by "
        "`scripts/score_practice.py`; every run is in `output/usage_log.json` and every report is in `output/reports/`.",
        "",
        "## Summary",
        "",
        "**Table 1: Practice Score Summary**",
        "",
        "| Documents fully correct | Fields correct | Decisions correct | Total cost (12 docs) | Avg cost per doc (cache warm) | Avg output tokens |",
        "|---|---|---|---|---|---|",
        f"| {full}/12 | {fields}/{12 * len(FIELDS)} | {decisions}/12 | ${cost:.6f} | "
        f"${sum(u.cost_usd for u in warm) / len(warm):.6f} | {sum(u.output_tokens for *_, u in rows) / 12:.0f} |",
        "",
        "## Every document",
        "",
        "**Table 2: Practice Results by Document**",
        "",
        "| Document | Type | Result | Wrong fields (got → expected) | Decision | Reason | Cost |",
        "|---|---|---|---|---|---|---|",
    ]
    for k, got, wrong, u in rows:
        diffs = "; ".join(f"{f}: {got[f]} → {k[f]}" for f in wrong)
        lines.append(f"| {k['file']} | {Path(k['file']).suffix[1:].upper()} | {'✅ correct' if not wrong else '❌ wrong'} "
                     f"| {diffs} | {got['decision']} | {got['reason'].replace('|', '/')} | ${u.cost_usd:.6f} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}  ({full}/12 fully correct)")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    asyncio.run(main())
